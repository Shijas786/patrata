// Builds one desk into dist/<desk>/: the shared app, the desk's own files, the browser
// runtime, and the generated network and discovery files.
//
//   node tools/build.mjs <desk> [--partner-network URL] [--partner-page URL] [--repo URL] [--check]
//
// A desk that calls a partner (desk.json "partner") needs --partner-network, the
// partner's network URL, such as http://localhost:8081/rajya_desk.
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { RuleEngine } from "../app/js/engine.js";
import { Fields } from "../app/js/fields.js";

/**
 * Assembles a desk's static site.
 */
class DeskBuilder {
  static ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

  static SKILL = join(DeskBuilder.ROOT, "vendor", "agentify-website");

  /**
   * Read the command line.
   *
   * :param argv: The arguments after the script name.
   * :return: The desk name and options.
   */
  static parseArgs(argv) {
    const options = {desk: null, check: false, repo: "https://github.com/Shijas786/patrata"};
    for (let index = 0; index < argv.length; index += 1) {
      const arg = argv[index];
      if (arg === "--check") {
        options.check = true;
      } else if (arg === "--partner-network" || arg === "--partner-page" || arg === "--repo") {
        options[arg.slice(2).replace(/-(.)/g, (match, letter) => letter.toUpperCase())] = argv[index + 1];
        index += 1;
      } else {
        options.desk = arg;
      }
    }
    if (!options.desk) {
      throw new Error("Usage: node tools/build.mjs <desk> [--partner-network URL] [--partner-page URL] [--repo URL] [--check]");
    }
    return options;
  }

  /**
   * Replace every key of a map in a text.
   *
   * :param text: The text.
   * :param map: Replacement by placeholder.
   * :return: The text with every placeholder replaced.
   */
  static fill(text, map) {
    let filled = text;
    for (const [key, value] of Object.entries(map)) {
      filled = filled.split(key).join(value);
    }
    return filled;
  }

  /**
   * Escape text for HTML.
   *
   * :param text: Plain text.
   * :return: The text, safe inside HTML.
   */
  static html(text) {
    return String(text).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
  }

  /**
   * Build the desk.
   *
   * :param argv: The arguments after the script name.
   */
  static main(argv) {
    const options = DeskBuilder.parseArgs(argv);
    const source = join(DeskBuilder.ROOT, "desks", options.desk);
    const out = join(DeskBuilder.ROOT, "dist", options.desk);
    const desk = JSON.parse(readFileSync(join(source, "desk.json"), "utf8"));
    const schemes = JSON.parse(readFileSync(join(source, "schemes.json"), "utf8"));

    const problems = RuleEngine.validate(schemes, Fields.BY_ID);
    if (problems.length) {
      throw new Error(`schemes.json is not valid:\n- ${problems.join("\n- ")}`);
    }

    const placeholders = {};
    if (desk.partner) {
      if (!options.partnerNetwork) {
        throw new Error(`Desk "${options.desk}" calls a partner: pass --partner-network URL.`);
      }
      const network = new URL(options.partnerNetwork);
      placeholders.__PARTNER_NETWORK__ = network.href;
      placeholders.__PARTNER_ORIGIN__ = network.origin;
      // The runtime names a partner tool after the URL's whole path.
      placeholders.__PARTNER_TOOL__ = network.pathname.replace(/^\/+|\/+$/g, "").replace(/[^A-Za-z0-9_]/g, "_");
      desk.partner.pageUrl = options.partnerPage || new URL("./", network).href;
    }

    if (!options.check) {
      rmSync(out, {recursive: true, force: true});
    }
    mkdirSync(out, {recursive: true});
    cpSync(join(DeskBuilder.ROOT, "app"), out, {recursive: true});
    cpSync(join(DeskBuilder.SKILL, "runtime"), join(out, "runtime"), {recursive: true});
    cpSync(join(source, "schemes.json"), join(out, "schemes.json"));
    cpSync(join(source, "links.json"), join(out, "links.json"));

    const hocon = `${desk.network}.hocon`;
    writeFileSync(join(out, hocon), DeskBuilder.fill(readFileSync(join(source, hocon), "utf8"), placeholders));
    writeFileSync(join(out, "agent-manifest.json"), DeskBuilder.fill(readFileSync(join(source, "agent-manifest.json"), "utf8"), placeholders));
    writeFileSync(join(out, "js", "desk-data.js"), [
      "// Generated by tools/build.mjs from desk.json and schemes.json. Do not edit.",
      `export const DESK = ${JSON.stringify(desk, null, 2)};`,
      `export const SCHEMES = ${JSON.stringify(schemes, null, 2)};`,
      "",
    ].join("\n"));

    const partnerBlock = desk.partner
      ? `<p>For ${DeskBuilder.html(desk.partner.what)}, visit <a id="partner-link" href="${DeskBuilder.html(desk.partner.pageUrl)}">${DeskBuilder.html(desk.partner.label)}</a>, or ask the assistant: it asks ${DeskBuilder.html(desk.partner.label)} for you, after you agree.</p>`
      : "";
    const page = {
      "{{partnerBlock}}": partnerBlock,
      "{{repoUrl}}": DeskBuilder.html(options.repo),
      "{{primary}}": desk.theme.primary,
      "{{accent}}": desk.theme.accent,
    };
    for (const key of ["title", "tagline", "lede", "devanagari", "brand", "scope", "assistantLine", "network"]) {
      page[`{{${key}}}`] = DeskBuilder.html(desk[key]);
    }
    writeFileSync(join(out, "index.html"), DeskBuilder.fill(readFileSync(join(out, "index.html"), "utf8"), page));
    writeFileSync(join(out, "favicon.svg"), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="14" fill="${desk.theme.primary}"/><path d="M18 33l10 10 19-22" fill="none" stroke="#fff" stroke-width="7" stroke-linecap="round" stroke-linejoin="round"/></svg>\n`);

    const publicFiles = ["agent-manifest.json", `${desk.network}.network.json`, "links.json", "agent-mcp.json", "schemes.json", ".well-known/nsdeploy.json", ".well-known/nsdeploy-agent.json"];
    const headers = publicFiles.map((file) => `/${file}\n  Access-Control-Allow-Origin: *`);
    headers.push("/runtime/sandbox-worker.js\n  Content-Security-Policy: default-src 'none'; script-src blob:; connect-src 'none'; worker-src 'none'");
    writeFileSync(join(out, "_headers"), `${headers.join("\n")}\n`);
    writeFileSync(join(out, ".nojekyll"), "");

    const args = [join(DeskBuilder.SKILL, "scripts", "build_network.mjs"), join(out, hocon), "--manifest", join(out, "agent-manifest.json")];
    if (options.check && existsSync(join(out, `${desk.network}.network.json`))) {
      args.push("--check");
    }
    execFileSync(process.execPath, args, {stdio: "inherit"});
    console.log(`Built ${out}`);
  }
}

DeskBuilder.main(process.argv.slice(2));
